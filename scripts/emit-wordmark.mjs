import fs from "node:fs";
const d = JSON.parse(fs.readFileSync("scripts/logo-data.json", "utf8"));
const W = d.wordW;
const wordD = d.body.join(" ");
const capsD = d.caps.join(" ");
const oc = { cx: (d.o.x1 + d.o.x2) / 2, cy: (d.o.y1 + d.o.y2) / 2 };
const VB_W = Math.ceil(W + 8);
const VB_H = 150;
const wave = (() => {
  const y = 111, a = 3.2, seg = 8, n = Math.ceil(W / seg);
  let p = `M0 ${y}`;
  for (let i = 0; i < n; i++) {
    const x0 = i * seg, x1 = x0 + seg;
    const cy = y + (i % 2 ? a : -a);
    p += ` Q${x0 + seg / 2} ${cy} ${x1} ${y}`;
  }
  return p;
})();

const tsx = `/* Generated by scripts/emit-wordmark.mjs from Sniglet ExtraBold + Poppins SemiBold outlines.
 * Custom lockup: the fish swims in as the apostrophe, a bubble glint sits in the o,
 * a coral water line runs under the name, the caps are set to the name's exact width. */
import clsx from "clsx";

export const WORDMARK_RATIO = ${(VB_W / VB_H).toFixed(4)};

export default function Wordmark({ tone = "dark", className, id = "wm" }: { tone?: "dark" | "light"; className?: string; id?: string }) {
  const light = tone === "light";
  const g1 = light ? "#ffffff" : "#0a3b61";
  const g2 = light ? "#bff3ff" : "#0f5f8f";
  const caps = light ? "#33d6f2" : "#12a6c9";
  return (
    <svg viewBox="0 0 ${VB_W} ${VB_H}" className={clsx("block", className)} role="img" aria-label="Jason's Aquarium Service">
      <defs>
        <linearGradient id={\`\${id}-w\`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0" stopColor={g1} />
          <stop offset="1" stopColor={g2} />
        </linearGradient>
        <linearGradient id={\`\${id}-f\`} x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" stopColor="#33d6f2" />
          <stop offset="1" stopColor="#0f5f8f" />
        </linearGradient>
        <radialGradient id={\`\${id}-b\`} cx="0.4" cy="0.35" r="0.65">
          <stop offset="0" stopColor="#33d6f2" stopOpacity="0.55" />
          <stop offset="1" stopColor="#33d6f2" stopOpacity="0.08" />
        </radialGradient>
      </defs>
      <g transform="translate(4 0)">
        {/* bubble inside the o */}
        <circle cx="${oc.cx.toFixed(1)}" cy="${(oc.cy + 1).toFixed(1)}" r="13.5" fill={\`url(#\${id}-b)\`} />
        <ellipse cx="${(oc.cx - 4.5).toFixed(1)}" cy="${(oc.cy - 5).toFixed(1)}" rx="4.2" ry="2.8" fill="#ffffff" opacity={light ? 0.95 : 0.9} transform="rotate(-25 ${(oc.cx - 4.5).toFixed(1)} ${(oc.cy - 5).toFixed(1)})" />
        {/* the name */}
        <path d="${wordD}" fill={\`url(#\${id}-w)\`} />
        {/* fish as the apostrophe */}
        <g transform="translate(${(d.apos.x - 12).toFixed(1)} ${(d.apos.y1 - 18).toFixed(1)}) rotate(-16 22 20)">
          <path d="M3 20.5 C9.5 9.5 23.5 9.5 31.5 20.5 C23.5 31.5 9.5 31.5 3 20.5 Z" fill={\`url(#\${id}-f)\`} />
          <path d="M30.5 20.5 L39 13.5 L36.8 20.5 L39 27.5 Z" fill="#ff6a4d" />
          <circle cx="10.5" cy="18.6" r="1.9" fill="#04213a" />
          <circle cx="11.1" cy="18" r="0.6" fill="#fff" />
          <circle cx="37" cy="6.5" r="2.1" fill="none" stroke="#33d6f2" strokeWidth="1.5" />
          <circle cx="42" cy="1.8" r="1.3" fill="none" stroke="#33d6f2" strokeWidth="1.3" />
        </g>
        {/* water line */}
        <path d="${wave}" fill="none" stroke="#ff6a4d" strokeWidth="2.6" strokeLinecap="round" opacity="0.95" />
        {/* caps set to the name width */}
        <g transform="translate(0 -9) scale(${d.capsScale.toFixed(4)})">
          <path d="${capsD}" fill={caps} />
        </g>
      </g>
    </svg>
  );
}
`;
fs.writeFileSync("components/Wordmark.tsx", tsx);
// favicon from the mark
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="#04213a"/><g transform="translate(9 12) scale(1.05)"><path d="M3 20.5 C9.5 9.5 23.5 9.5 31.5 20.5 C23.5 31.5 9.5 31.5 3 20.5 Z" fill="#33d6f2"/><path d="M30.5 20.5 L39 13.5 L36.8 20.5 L39 27.5 Z" fill="#ff6a4d"/><circle cx="10.5" cy="18.6" r="1.9" fill="#04213a"/><circle cx="37" cy="6.5" r="2.1" fill="none" stroke="#33d6f2" stroke-width="1.6"/><circle cx="42" cy="1.8" r="1.3" fill="none" stroke="#33d6f2" stroke-width="1.3"/></g></svg>`;
fs.writeFileSync("app/icon.svg", icon);
console.log("wrote Wordmark.tsx", VB_W, VB_H);
